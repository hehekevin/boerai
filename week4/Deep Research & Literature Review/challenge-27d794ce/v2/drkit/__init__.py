"""drkit · 深度研究与文献综述赛道引擎（stdlib only）

职责边界：引擎只做确定性簿记；语义判断（相关性、分类、写作）由加载
Skill 的 Agent 完成，中间产物一律落盘为 JSON，保证可复跑、可审计。

模块：
- identity    文献记录身份判定与去重（DOI/标题/作者+年模糊），合并留痕
- qplan       研究问题拆解与检索计划校验：子问题可独立检索、依赖无环、
              按证据充分性（而非轮数）决定停止
- iterloop    检索迭代账本：每轮有信号与决定，支持回滚与停止判据
- screen      PRISMA 式纳排筛选记录：逐条决定+理由码+证据片段，双人分歧留痕
- evidence    证据矩阵：结论句 ↔ 原文摘录 ↔ 定位（页/段/行），无摘录+定位
              的断言被拒绝；冲突对必须给出双方证据比较，拒绝"尚存争议"搪塞
- synthesis   综合审计：每句结论分类为 材料事实/合理推断/无法确定 并校验
              支撑；每个子问题必须被覆盖或显式标注缺口
- gaps        空白分析：研究空白必须建立在实际检索记录上（searched_* 引用
              真实 query_id；未检索范围必须标记 speculation）
- trendstat   趋势统计：年度分布、主题-年度计数、拐点信号；趋势断言必须
              回指真实统计行，幻影年份被拒绝
"""

